#!/usr/bin/env python3
"""Build or verify the checked-in JAHIDS skill catalog."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

import yaml

ROOT = Path(__file__).resolve().parents[1]
SKILLS = ROOT / "skills"
JSON_OUTPUT = ROOT / "catalog" / "skills.json"
MARKDOWN_OUTPUT = ROOT / "catalog" / "README.md"


def build_catalog() -> list[dict[str, str]]:
    entries: list[dict[str, str]] = []
    for skill_file in sorted(SKILLS.glob("*/SKILL.md")):
        text = skill_file.read_text(encoding="utf-8")
        closing = text.find("\n---\n", 4)
        if not text.startswith("---\n") or closing < 0:
            raise ValueError(f"{skill_file}: invalid frontmatter delimiters")
        metadata = yaml.safe_load(text[4:closing])
        if not isinstance(metadata, dict):
            raise ValueError(f"{skill_file}: frontmatter must be a mapping")
        entries.append({
            "name": str(metadata["name"]),
            "description": str(metadata["description"]),
            "path": skill_file.relative_to(ROOT).as_posix(),
        })
    return entries


def render_json(entries: list[dict[str, str]]) -> str:
    return json.dumps(
        {"schema_version": 1, "skills": entries},
        indent=2,
        ensure_ascii=False,
    ) + "\n"


def render_markdown(entries: list[dict[str, str]]) -> str:
    lines = [
        "# JAHIDS.AI Skills Catalog",
        "",
        f"**{len(entries)} skills** in the independent JAHIDS.AI skills library.",
        "",
        "| Skill | Description |",
        "|---|---|",
    ]
    for entry in entries:
        lines.append(
            f"| [{entry['name']}](../{entry['path']}) | {entry['description']} |"
        )
    lines.extend(["", "Generated by scripts/build_catalog.py. Do not edit by hand.", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    entries = build_catalog()
    expected = {
        JSON_OUTPUT: render_json(entries),
        MARKDOWN_OUTPUT: render_markdown(entries),
    }
    stale: list[str] = []
    for path, content in expected.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        print("Stale generated catalog files: " + ", ".join(stale))
        print("Run python scripts/build_catalog.py")
        return 1
    if args.check:
        print(f"PASS: catalog matches {len(entries)} skill files")
    else:
        print(f"Generated catalog for {len(entries)} skills")
    return 0


if __name__ == "__main__":
    sys.exit(main())
